"""Turn check_results into a monthly range-partitioned table (plan V2, A-1).

Revision ID: e6f7a8b9c0d1
Revises: d5e6f7a8b9c0
Create Date: 2026-08-06

Why
───
``check_results`` is the only table whose size is driven by time rather than by
configuration: ~60 500 rows/day, 3 GB at 90 days of retention (measured, see
plan_v2.md § "Résultats A-0"). Two consequences the plan set out to fix:

* the nightly ``DELETE`` in ``services/retention.py`` is the worst possible
  write pattern for PostgreSQL on that table — bloat plus autovacuum debt every
  single night, forever;
* every analytical query (``compute_daily_history`` & co) seq-scans the whole
  heap because 7 % selectivity on a scattered heap makes the planner ignore the
  btree.

``PARTITION BY RANGE (checked_at)``, one partition per UTC month, turns the
purge into ``DROP TABLE`` (O(1), zero bloat) and lets the planner prune whole
months on any bounded query.

How — no bulk copy
──────────────────
The obvious migration (build a new partitioned table, copy 4.9 M rows, swap)
needs a second copy of the data on disk and a long window where writes must be
replayed. It is avoided entirely: the existing table is *renamed* and attached
as-is as the first partition.

    check_results ──rename──► check_results_legacy ──ATTACH──► partition
                                                                [MINVALUE, cutover)

``cutover`` is the start of the *next* UTC month, so no month is ever split
across the legacy partition and a monthly one. The legacy partition then ages
out on its own: once its whole range is past retention, ``retention.py`` drops
it like any other. Nothing is copied, nothing is deleted, and the heap is
touched only by the scans PostgreSQL needs for validation:

* one seq scan to validate the range CHECK that lets ``ATTACH`` skip *its* scan;
* one scan per cloned foreign key;
* one index build for the new primary key.

The 428 MB ``ix_check_results_monitor_checked`` is **not** rebuilt: the parent
index is created ``ON ONLY`` and the legacy partition's existing index is
attached to it.

Primary key
───────────
A partitioned table's unique constraints must contain the partition key, so the
PK becomes ``(id, checked_at)``. Consequence to be aware of: ``id`` alone is no
longer globally unique — PostgreSQL cannot enforce that across partitions. It
is a client-side ``uuid4`` with no cross-table reference (nothing in the schema
has a foreign key to ``check_results``), so this is a formality, not a risk.

Duration on the measured production table (4.9 M rows, 3 GB): a few minutes,
dominated by the primary-key build. The table is unavailable for the duration.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import UTC, datetime, timedelta

from alembic import op
from sqlalchemy import text

revision: str = "e6f7a8b9c0d1"
down_revision: str | None = "d5e6f7a8b9c0"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

# Kept in sync with whatisup.core.partitions (imported there rather than here so
# the migration stays independent of the application package).
_MONTHS_AHEAD = 3


def _month_start(moment: datetime) -> datetime:
    return moment.astimezone(UTC).replace(day=1, hour=0, minute=0, second=0, microsecond=0)


def _next_month(start: datetime) -> datetime:
    # Normalise first: 31 January + 32 days would otherwise land in March.
    return _month_start(_month_start(start) + timedelta(days=32))


def _literal(moment: datetime) -> str:
    return f"TIMESTAMPTZ '{moment.isoformat()}'"


def _partition_name(start: datetime) -> str:
    return f"check_results_{start.year:04d}_{start.month:02d}"


def _constraint_names(bind, table: str, contype: str) -> list[str]:
    """Names of ``table``'s constraints of a given ``pg_constraint.contype``.

    Discovered rather than hard-coded: primary key and foreign key names on this
    table were generated by PostgreSQL and an installation that once restored
    from a dump may spell them differently.
    """
    # contype is a PostgreSQL "char" (one byte), which asyncpg will not let a
    # Python str bind to — cast or not. It is inlined instead; the caller-side
    # whitelist keeps that safe.
    assert contype in {"p", "f", "c"}
    rows = bind.execute(
        text(
            "SELECT conname FROM pg_constraint "
            f"WHERE conrelid = to_regclass(:t) AND contype = '{contype}' ORDER BY conname"
        ),
        {"t": table},
    ).all()
    return [r[0] for r in rows]


def upgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        # SQLite (tests) has no partitioning; the ORM model is identical on both
        # because ``postgresql_partition_by`` is a dialect-scoped kwarg.
        return

    cutover = _next_month(_month_start(datetime.now(UTC)))

    # ── 1. Move the existing table out of the way, names included ────────────
    op.execute("ALTER TABLE check_results RENAME TO check_results_legacy")
    op.execute(
        "ALTER INDEX IF EXISTS ix_check_results_monitor_checked "
        "RENAME TO ix_cr_legacy_monitor_checked"
    )
    op.execute("ALTER INDEX IF EXISTS ix_cr_checked_at_brin RENAME TO ix_cr_legacy_checked_at_brin")
    # The parent will own the canonical constraint names. The legacy foreign
    # keys go away entirely: the parent's are cloned onto every partition at
    # ATTACH time, and keeping both would double the work on every cascade.
    for name in _constraint_names(bind, "check_results_legacy", "f"):
        op.execute(f'ALTER TABLE check_results_legacy DROP CONSTRAINT "{name}"')
    # Likewise the single-column primary key: the parent's (id, checked_at) is
    # cloned down, so building one here first would build the same index twice.
    for name in _constraint_names(bind, "check_results_legacy", "p"):
        op.execute(f'ALTER TABLE check_results_legacy DROP CONSTRAINT "{name}"')

    # ── 1b. Park the rows the legacy partition cannot hold ───────────────────
    # Nothing guarantees the existing table stops at the cut-over: a probe with
    # a skewed clock, or a re-run after a downgrade, leaves rows dated past it.
    # They would fail the range CHECK below and abort the whole migration, so
    # they are set aside and re-inserted through the parent once the monthly
    # partitions exist (§5b) — routed properly instead of blocking the upgrade.
    # Normally this moves zero rows, and the BRIN index on checked_at keeps the
    # lookup cheap when it does not.
    op.execute("DROP TABLE IF EXISTS check_results_future_hold")
    op.execute(
        "CREATE TABLE check_results_future_hold "
        "(LIKE check_results_legacy INCLUDING DEFAULTS INCLUDING STORAGE)"
    )
    op.execute(
        "WITH moved AS ("
        "  DELETE FROM check_results_legacy "
        f"  WHERE checked_at >= {_literal(cutover)} RETURNING *"
        ") INSERT INTO check_results_future_hold SELECT * FROM moved"
    )

    # ── 2. The partitioned parent, shaped exactly like the old table ─────────
    op.execute(
        "CREATE TABLE check_results "
        "(LIKE check_results_legacy INCLUDING DEFAULTS INCLUDING CONSTRAINTS INCLUDING STORAGE) "
        "PARTITION BY RANGE (checked_at)"
    )
    op.execute(
        "ALTER TABLE check_results ADD CONSTRAINT check_results_monitor_id_fkey "
        "FOREIGN KEY (monitor_id) REFERENCES monitors (id) ON DELETE CASCADE"
    )
    op.execute(
        "ALTER TABLE check_results ADD CONSTRAINT check_results_probe_id_fkey "
        "FOREIGN KEY (probe_id) REFERENCES probes (id) ON DELETE CASCADE"
    )

    # ── 3. Attach the old table as the historical partition ──────────────────
    # A *valid* CHECK proving the partition constraint is what lets ATTACH skip
    # its own scan of the 3 GB heap. Adding it costs one scan of its own, but a
    # cheaper one: no partition routing, no per-row bound comparison against a
    # catalog expression. (NOT VALID + VALIDATE would buy nothing here — the
    # whole migration runs in a single transaction, so the exclusive lock is
    # held until commit either way.)
    op.execute(
        "ALTER TABLE check_results_legacy ADD CONSTRAINT check_results_legacy_range "
        f"CHECK (checked_at IS NOT NULL AND checked_at < {_literal(cutover)})"
    )
    op.execute(
        "ALTER TABLE check_results ATTACH PARTITION check_results_legacy "
        f"FOR VALUES FROM (MINVALUE) TO ({_literal(cutover)})"
    )
    # Redundant once attached — the partition bound enforces the same thing.
    op.execute("ALTER TABLE check_results_legacy DROP CONSTRAINT check_results_legacy_range")

    # ── 4. Indexes: adopt the legacy ones instead of rebuilding them ─────────
    # ON ONLY creates the parent index without touching partitions; ALTER INDEX
    # … ATTACH PARTITION then adopts the (already built) legacy index. The
    # DESC ordering is load-bearing — fetch_latest_results' LATERAL depends on
    # it (see models/result.py).
    op.execute(
        "CREATE INDEX ix_check_results_monitor_checked ON ONLY check_results "
        "(monitor_id, checked_at DESC)"
    )
    op.execute(
        "ALTER INDEX ix_check_results_monitor_checked ATTACH PARTITION ix_cr_legacy_monitor_checked"
    )
    op.execute(
        "CREATE INDEX ix_cr_checked_at_brin ON ONLY check_results "
        "USING brin (checked_at) WITH (pages_per_range = 32)"
    )
    op.execute("ALTER INDEX ix_cr_checked_at_brin ATTACH PARTITION ix_cr_legacy_checked_at_brin")

    # ── 5. Future partitions + the safety net ────────────────────────────────
    # DEFAULT catches rows no monthly partition covers (a probe with a broken
    # clock, or a server that stayed down past the head-room) instead of
    # rejecting the insert and losing the result. core.partitions drains it
    # when it later creates the real partition for that month.
    op.execute("CREATE TABLE check_results_default PARTITION OF check_results DEFAULT")
    start = cutover
    for _ in range(_MONTHS_AHEAD + 1):
        end = _next_month(start)
        op.execute(
            f'CREATE TABLE "{_partition_name(start)}" PARTITION OF check_results '
            f"FOR VALUES FROM ({_literal(start)}) TO ({_literal(end)})"
        )
        start = end

    # ── 5b. Give the parked rows back, now that routing can place them ───────
    # Done before the primary key exists so the insert pays no index upkeep.
    # Anything beyond the provisioned head-room lands in the DEFAULT partition,
    # which is precisely what it is for.
    op.execute("INSERT INTO check_results SELECT * FROM check_results_future_hold")
    op.execute("DROP TABLE check_results_future_hold")

    # ── 6. Primary key, built once across every partition ────────────────────
    op.execute(
        "ALTER TABLE check_results ADD CONSTRAINT check_results_pkey PRIMARY KEY (id, checked_at)"
    )


def downgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        return

    # Detach the historical partition, fold every other partition's rows back
    # into it, then drop the parent. Only the post-cut-over rows are copied —
    # the bulk of the history never moves.
    #
    # Unless the legacy partition is already gone: past one retention window it
    # has expired and been dropped like any other. A rollback that late must
    # still work, so the un-partitioned table is rebuilt from scratch instead.
    legacy_exists = (
        bind.execute(text("SELECT to_regclass('check_results_legacy')")).scalar() is not None
    )
    if legacy_exists:
        op.execute("ALTER TABLE check_results DETACH PARTITION check_results_legacy")
    else:
        op.execute(
            "CREATE TABLE check_results_legacy "
            "(LIKE check_results INCLUDING DEFAULTS INCLUDING STORAGE)"
        )
    op.execute("INSERT INTO check_results_legacy SELECT * FROM check_results")
    op.execute("DROP TABLE check_results")

    # Constraints cloned from the parent survive the detach under names
    # PostgreSQL chose; discover and replace them with the canonical ones.
    for name in _constraint_names(bind, "check_results_legacy", "f"):
        op.execute(f'ALTER TABLE check_results_legacy DROP CONSTRAINT "{name}"')
    for name in _constraint_names(bind, "check_results_legacy", "p"):
        op.execute(f'ALTER TABLE check_results_legacy DROP CONSTRAINT "{name}"')
    rows = bind.execute(
        text(
            "SELECT conname FROM pg_constraint "
            "WHERE conrelid = to_regclass('check_results_legacy') AND contype = 'c' "
            "AND pg_get_constraintdef(oid) LIKE '%checked_at%'"
        )
    ).all()
    for (name,) in rows:
        op.execute(f'ALTER TABLE check_results_legacy DROP CONSTRAINT "{name}"')

    op.execute(
        "ALTER TABLE check_results_legacy ADD CONSTRAINT check_results_pkey PRIMARY KEY (id)"
    )
    op.execute(
        "ALTER TABLE check_results_legacy ADD CONSTRAINT check_results_monitor_id_fkey "
        "FOREIGN KEY (monitor_id) REFERENCES monitors (id) ON DELETE CASCADE"
    )
    op.execute(
        "ALTER TABLE check_results_legacy ADD CONSTRAINT check_results_probe_id_fkey "
        "FOREIGN KEY (probe_id) REFERENCES probes (id) ON DELETE CASCADE"
    )
    op.execute("ALTER TABLE check_results_legacy RENAME TO check_results")
    # Adopt the legacy indexes back under their canonical names when they are
    # there; build them when the partition had already expired (above).
    op.execute(
        "ALTER INDEX IF EXISTS ix_cr_legacy_monitor_checked "
        "RENAME TO ix_check_results_monitor_checked"
    )
    op.execute("ALTER INDEX IF EXISTS ix_cr_legacy_checked_at_brin RENAME TO ix_cr_checked_at_brin")
    op.execute(
        "CREATE INDEX IF NOT EXISTS ix_check_results_monitor_checked "
        "ON check_results (monitor_id, checked_at DESC)"
    )
    op.execute(
        "CREATE INDEX IF NOT EXISTS ix_cr_checked_at_brin "
        "ON check_results USING brin (checked_at) WITH (pages_per_range = 32)"
    )
